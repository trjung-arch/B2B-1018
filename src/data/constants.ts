export function inferCategoryFromProductName(name: string): OrderProductCategory {
  if (!name) return '스크럽';
  for (const [cat, prods] of Object.entries(ORDER_PRODUCTS_BY_CATEGORY)) {
    if (prods.some(p => name.includes(p) || p.includes(name))) {
      return cat as OrderProductCategory;
    }
  }
  if (name.includes('스크럽') || name.includes('상의')) return '스크럽';
  if (name.includes('코트') || name.includes('자켓') || name.includes('가운')) return '자켓';
  if (name.includes('가디건') || name.includes('니트')) return '가디건';
  if (name.includes('팬츠') || name.includes('하의') || name.includes('바지')) return '팬츠';
  if (name.includes('에이프런') || name.includes('앞치마') || name.includes('캡') || name.includes('슬리퍼')) return '기타';
  return '스크럽';
}

